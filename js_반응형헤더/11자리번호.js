// small li를 클릭하면, 같은 순서의 large li만 보이게
$(function () {
  $(".small li").on("click", function () {
    const i = $(this).index(); //
    // $(".small li"): "작은 이미지(썸네일) 목록들 중에서,"
    // .click: "누군가 하나를 클릭하면,"
    // function () { ... }: "중괄호 안의 명령들을 실행해라!"
    // const i: i라는 이름의 **변수(그릇)**를 만듭니다. (다음에 또 쓸 수 있게 값을 담아두는 거예요.)
    // $(this): 클릭 이벤트가 발생한 바로 그 썸네일
    // .index(): 그 썸네일이 몇 번째 자식인지 번호를 알아냅니다. 클릭한 li의 순서(0, 1, 2, 3...)
    // 해석: "방금 클릭한 놈이 몇 번인지 알아내서 i라는 그릇에 담아둬!"

    // large 영역: 모두 숨기고, 선택한 것만 보이게
    $(".large li").hide();
    $(".large li").eq(i).show();
    // .eq(i): 그중에서 아까 i에 담아둔 번호와 똑같은 순서의 이미지만 딱 집어냅니다.

    // small 영역: 선택된 썸네일에만 on 클래스
    $(".small li").removeClass("on");
    $(this).addClass("on");
  });
});

// 요약하자면 이렇습니다!
// 클릭하면 (click)
// 내가 몇 번째인지 번호표를 확인하고 (this, index)
// 그 번호를 변수에 저장한 뒤 (i)
// 큰 이미지 중 그 번호랑 똑같은 놈만 보여주고 (eq(i))
// 나머지 이미지와 썸네일들은 비활성화 시킨다!

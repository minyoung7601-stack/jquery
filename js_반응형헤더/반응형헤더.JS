$(function () {
  $(".bar").on("click", function () {
    $("nav").stop().animate({ right: "2rem" });
    $(".bar").hide();
    $(".close").show();
  });
  $(".close").on("click", function () {
    $("nav").stop().animate({ right: "-500px" });
    $(".bar").show();
    $(".close").hide();
  });
});

// * 메뉴 열기: 햄버거 버튼(.bar)을 누르면 ->
// 메뉴(nav)가 (2rem으로 부드럽게 오른쪽 끝에서 안쪽으로 들어와서 )나타나고 ->
// 열기 버튼은 숨기고(.hide) -> 닫기 버튼을 보여준다(.show).

//  * 메뉴 닫기: 닫기 버튼(.close)을 누르면 ->
// 메뉴(nav)가 다시 화면 오른쪽 바깥(마이너스 영역)으로 밀어내서 숨고 ->
// 닫았으니 닫기 버튼은 숨기고 -> 다시 열기(bar) 버튼을 보여준다.

